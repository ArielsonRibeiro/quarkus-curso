package org.br.mineradora.rsproxy;

public class PropostaNaoLocalizadaException extends Exception {

	/**
	 * 
	 */
	private static final long serialVersionUID = 1L;

	public PropostaNaoLocalizadaException() {
		super();
	}

	public PropostaNaoLocalizadaException(String message, Throwable cause) {
		super(message, cause);
	}

	public PropostaNaoLocalizadaException(String message) {
		super(message);
	}

	public PropostaNaoLocalizadaException(Throwable cause) {
		super(cause);
	}

}
